#import <Cocoa/Cocoa.h>
#include <stdlib.h>
long qd_clipboard_change(void){ return (long)[NSPasteboard generalPasteboard].changeCount; }
char* qd_clipboard_text(void){
 @autoreleasepool {
  NSPasteboard *board=[NSPasteboard generalPasteboard];
  // nspasteboard.org markers plus 1Password's legacy type.
  for(NSString *type in @[@"org.nspasteboard.ConcealedType",@"org.nspasteboard.TransientType",@"org.nspasteboard.AutoGeneratedType",@"com.agilebits.onepassword"]){
   if([board.types containsObject:type])return NULL;
  }
  NSString *text=[board stringForType:NSPasteboardTypeString];
  return text?strdup(text.UTF8String):NULL;
 }
}
